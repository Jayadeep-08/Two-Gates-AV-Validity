"""Emit LaTeX macros for the Study 1 section.

Computed here: everything in numbers.json (Table I rows, lag retentions, the
episode-clustered conditional test) plus the formula-free rear-gap block, recomputed
from the banked NPC CSVs.

AUDIT dict: values that exist only in analysis artefacts of the closed project, each
listed with its source file so they are auditable rather than anonymous.

Run:  py -3.7 tiv_revision\\scripts\\study1_numbers.py
"""
import json, os
import numpy as np, pandas as pd
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("RPI_OUT") or os.path.abspath(os.path.join(HERE, ".."))
D = os.environ.get("RPI_DATA") or os.path.join(ROOT, "..", "data")
RNG = np.random.default_rng(42)
N = json.load(open(os.path.join(ROOT, "numbers.json")))
T = {r["key"]: r for r in N["table1"]}

AUDIT = {   # analysis/unified_mechanism.csv (covariance-share attribution)
    "oCovShareC": "99.8", "oCovShareA": "80.5", "oCovShareB": "122.7",
    "oCovShareBspeed": "-20.1", "oBspeedR": "+0.799",
    # ADVERSARIAL_AUDIT_2026-07-28.md §3 (common-outcome re-measurement)
    "oCommonC": "+0.7949", "oCommonB": "-0.6782", "oCommonA": "+0.0107",
    "oApartialLat": "-0.0994",
    # §5d (selection on a post-treatment variable) and coverage csv
    "oRearSelR": "+0.157", "oRearSelP": "0.13",
    "oFrontR": "+0.0623", "oFrontP": "0.72", "oFrontN": "37",
    "oRearCovPct": "43.6", "oRearZeroEp": "28",
    # CLAUDE.md closure note: saturation/pinning instances with a detector each
    "oSatCount": "five",
}

M = dict(AUDIT)
for k in "CABD":
    r = T[k]
    M[f"o{k}R"] = f"{r['r']:+.3f}"
    M[f"o{k}CI"] = f"[{r['ci_lo']:+.3f},\;{r['ci_hi']:+.3f}]".replace("+", "{+}").replace("-", "{-}")
    M[f"o{k}Nep"] = str(r["n_ep"])
    M[f"o{k}Npairs"] = f"{r['n_pairs']:,}".replace(",", "{,}")
    M[f"o{k}Rho"] = f"{r['rho_mean']:.3f}"
    M[f"o{k}Partial"] = f"{r['r_partial']:+.3f}"
M["oBcollin"] = f"{T['B']['collinearity']:+.4f}"
M["oDautocorr"] = f"{T['D']['collinearity']:+.4f}"
for k in "CAD":
    rr = [s["retention"] for s in N["lag"][k] if s["k"] == 6]
    if rr: M[f"o{k}Ret"] = f"{rr[0]:.2f}"
M["oBkmax"] = str(max(s["k"] for s in N["lag"]["B"]))

c = N["conditional"]
k1 = "kinematic state at T+1"; k2 = "state + rho_T+1 + sev_T+1"
M["oCondUncond"] = "+0.380"
M["oCondN"] = f"{c[k1]['n']:,}".replace(",", "{,}")
M["oCondClusters"] = str(c[k1]["n_clusters"])
M["oCondState"] = f"{c[k1]['r']:+.3f}"
M["oCondStateCI"] = f"[{c[k1]['lo']:+.3f},\;{c[k1]['hi']:+.3f}]".replace("+", "{+}").replace("-", "{-}")
M["oCondFull"] = f"{c[k2]['r']:+.3f}"
M["oCondFullCI"] = f"[{c[k2]['lo']:+.3f},\;{c[k2]['hi']:+.3f}]".replace("+", "{+}").replace("-", "{-}")
M["oVarRemoved"] = f"{100 * (1 - c[k1]['r'] ** 2 / 0.3798 ** 2):.1f}"

# ---- formula-free rear gap
truthy = lambda s: s.astype(str).str.strip().str.lower().isin(["true", "1", "1.0"])
n = pd.read_csv(os.path.join(D, "scenario_c_npc_rss.csv"))
n["sev"] = n.brake_intensity_t * n.brake_duration_ticks_t
r_ = n[truthy(n.rss_t1_rear_present)].copy()


def ep_r(df, extra=None):
    cols = {"s": ("sev", "mean"), "o": ("rss_t1_rear_gap", "mean")}
    if extra: cols["v"] = (extra, "mean")
    g = df.groupby("episode_id").agg(**cols).dropna()
    return g, stats.pearsonr(g.s, g.o)[0]


g, r0 = ep_r(r_)
lo, hi = np.percentile([stats.pearsonr(g.s.values[i], g.o.values[i])[0]
                        for i in RNG.integers(0, len(g), (10000, len(g)))], [2.5, 97.5])
M["oRearR"] = f"{r0:+.3f}"
M["oRearCI"] = f"[{lo:+.3f},\;{hi:+.3f}]".replace("+", "{+}").replace("-", "{-}")
M["oRearNep"] = str(len(g))
M["oRearNpairs"] = str(len(r_))
cnt = r_.groupby("episode_id").size()
for k in (2, 3, 4):
    s = r_[r_.episode_id.isin(cnt[cnt >= k].index)]
    M["oRearMin" + {2: "Two", 3: "Three", 4: "Four"}[k]] = f"{ep_r(s)[1]:+.3f}"
gg, _ = ep_r(r_, "speed_t1")
res = lambda y, X: y - np.column_stack([np.ones(len(y)), X]) @ np.linalg.lstsq(
    np.column_stack([np.ones(len(y)), X]), y, rcond=None)[0]
M["oRearPartial"] = f"{stats.pearsonr(res(gg.s.values, gg.v.values), res(gg.o.values, gg.v.values))[0]:+.3f}"
es = pd.read_csv(os.path.join(D, "scenario_c_npc_rss_episode_stats.csv"))[["episode_id", "escorts_spawned"]]
j = r_.merge(es, on="episode_id", how="left")
for lab, sel in (("Escort", j.escorts_spawned >= 1), ("Ambient", j.escorts_spawned == 0)):
    sub = j[sel]
    gq, rq = ep_r(sub)
    M["oRear" + lab] = f"{rq:+.3f}"
    M["oRear" + lab + "N"] = str(len(gq))

out = os.path.join(ROOT, "tables", "study1_macros.tex")
with open(out, "w") as fh:
    fh.write("% GENERATED by tiv_revision/scripts/study1_numbers.py -- do not hand-edit.\n")
    for k in sorted(M):
        fh.write("\\newcommand{\\%s}{%s}\n" % (k, M[k]))
print("wrote", out, "with", len(M), "macros")
for k in sorted(M): print(f"  \\{k} = {M[k]}")
