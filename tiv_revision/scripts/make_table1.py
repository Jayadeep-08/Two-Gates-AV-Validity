"""Generate Table I (.tex + .md) from numbers.json. DO NOT hand-edit the outputs."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("RPI_OUT") or os.path.abspath(os.path.join(HERE, ".."))
TAB = os.path.join(ROOT, "tables")
os.makedirs(TAB, exist_ok=True)

J = json.load(open(os.path.join(ROOT, "numbers.json")))
T = {r["key"]: r for r in J["table1"]}
LAG = J["lag"]

NAME = {"C": "C\\; Emergency braking", "A": "A\\; Lane change",
        "B": "B\\; Intersection yield", "D": "D\\; Open-road lane keep"}
SEV = {"C": "intensity $\\times$ duration", "A": "steer mag. $\\times$ ticks",
       "B": "realised yield speed", "D": "none ($v_t$ as proxy)"}
PARTIAL = {"C": "$-0.077^{a}$", "A": "$-0.099^{b}$", "B": "$-0.046^{c}$", "D": "---$^{d}$"}


def ret6(k):
    v = [s["retention"] for s in LAG[k] if s["k"] == 6]
    return f"{v[0]:.2f}" if v else "---$^{e}$"


def pfmt(p):
    return "$<\\!10^{-4}$" if p <= 1.1e-4 else f"${p * 1e4:.0f}\\!\\times\\!10^{{-4}}$"


def row(k):
    r = T[k]
    return (f"{NAME[k]} & {SEV[k]} & {r['n_ep']} & {r['n_pairs']} & "
            f"{r['rho_mean']:.3f} ({r['rho_sd']:.3f}) & "
            f"${r['r']:+.3f}$ $[{r['ci_lo']:+.3f},\\, {r['ci_hi']:+.3f}]$ & {pfmt(r['perm_p'])} & "
            f"${r['r_common']:+.3f}$ & {PARTIAL[k]} & {ret6(k)} \\\\")


tex = r"""% GENERATED by tiv_revision/scripts/make_table1.py -- do not hand-edit.
\begin{table*}[t]
\centering
\caption{Decision-severity association with downstream risk, by condition. The suite contains
two scripted-treatment conditions and two conditions with no treatment variable independent of the
measured state. Correlations are episode-level; CIs are 10{,}000-resample bootstrap and $p$-values
10{,}000-shuffle permutation.}
\label{tab:conditions}
\scriptsize
\setlength{\tabcolsep}{3.5pt}
\begin{tabular}{@{}llrrcccccc@{}}
\toprule
& & \multicolumn{2}{c}{$n$} & & \multicolumn{2}{c}{$r(\mathrm{severity},\, \rho_{t+1})$}
& common & partial & retention\\
\cmidrule(lr){3-4}\cmidrule(lr){6-7}
Condition & Severity variable & ep. & pairs & mean $\rho$ (sd) & $r$ \;[95\% CI] & perm $p$
& outcome$^{\ast}$ & $r$ & at $k{=}6$\\
\midrule
\multicolumn{10}{@{}l}{\emph{Scripted treatment}}\\
__C__
__A__
\addlinespace[2pt]
\multicolumn{10}{@{}l}{\emph{No treatment variable independent of the measured state}}\\
__B__
__D__
\bottomrule
\end{tabular}

\vspace{2pt}
\begin{minipage}{\textwidth}\scriptsize
$^{\ast}$\,Association with the one outcome computable from every condition's log,
$\max(0,\, 1 - v_{t+1}/15)$, in place of each condition's bespoke $\rho$.\\
$^{a}$\,Conditioned on $v_{t+1}$, the channel carrying 99.8\% of the severity covariance in C's
risk formula.
$^{b}$\,Conditioned on lateral deviation at $t{+}1$, the channel carrying 80.5\%.
$^{c}$\,Conditioned on $v_t$. B's severity variable \emph{is} $v_t$ (pair-level $r = +0.997$), so B
has no treatment independent of the conditioned state.
$^{d}$\,D's risk formula includes a lane-deviation term the banked log does not record, so no
available conditioning set covers its inputs; conditioning on $v_{t+1}$ alone leaves $+0.403$ and is
not comparable with the other rows.
$^{e}$\,B averages 3.0 pairs per episode, which limits the lag sweep to $k \leq 3$.
\end{minipage}
\end{table*}
"""
for k in "CABD":
    tex = tex.replace(f"__{k}__", row(k))
open(os.path.join(TAB, "table1.tex"), "w").write(tex)

NAME_MD = {"C": "C  Emergency braking", "A": "A  Lane change",
           "B": "B  Intersection yield-cross", "D": "D  Open-road lane keep"}
SEV_MD = {"C": "brake intensity x duration", "A": "steer magnitude x ticks",
          "B": "realised yield speed", "D": "none (v_t as pseudo-severity)"}
PM = {"C": "-0.077 (a)", "A": "-0.099 (b)", "B": "-0.046 (c)", "D": "— (d)"}

md = ["| Condition | Severity variable | ep. | pairs | mean rho (sd) | r | 95% CI | perm p "
      "| common outcome | partial r | retention k=6 |",
      "|---|---|---:|---:|---|---|---|---|---|---|---|"]
for grp, keys in [("**Scripted treatment**", "CA"),
                  ("**No treatment variable independent of the measured state**", "BD")]:
    md.append(f"| {grp} | | | | | | | | | | |")
    for k in keys:
        r = T[k]
        p = "<1e-4" if r["perm_p"] <= 1.1e-4 else f"{r['perm_p']:.4f}"
        ret = "— (e)" if ret6(k).startswith("---") else ret6(k)
        md.append(
            f"| {NAME_MD[k]} | {SEV_MD[k]} | {r['n_ep']} | {r['n_pairs']} "
            f"| {r['rho_mean']:.3f} ({r['rho_sd']:.3f}) | {r['r']:+.3f} "
            f"| [{r['ci_lo']:+.3f}, {r['ci_hi']:+.3f}] | {p} "
            f"| {r['r_common']:+.3f} | {PM[k]} | {ret} |")
md += [
    "",
    "(\\*) common outcome = association with max(0, 1 - v_{t+1}/15), the one outcome computable "
    "from every condition's log, in place of each condition's bespoke rho.",
    "",
    "- (a) conditioned on v_{t+1}, the channel carrying 99.8% of the severity covariance in C's formula.",
    "- (b) conditioned on lateral deviation at t+1, the channel carrying 80.5%.",
    "- (c) conditioned on v_t. B's severity variable *is* v_t (pair-level r = +0.997), so B has no "
    "treatment independent of the conditioned state.",
    "- (d) D's formula includes a lane-deviation term the banked log does not record, so no available "
    "conditioning set covers its inputs; conditioning on v_{t+1} alone leaves +0.403 and is not comparable.",
    "- (e) B averages 3.0 pairs per episode, limiting the lag sweep to k <= 3.",
]
open(os.path.join(TAB, "table1.md"), "w").write("\n".join(md) + "\n")
print("wrote", os.path.join(TAB, "table1.tex"), "and table1.md")
print("\n".join(md))
